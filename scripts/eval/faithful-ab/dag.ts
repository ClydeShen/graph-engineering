  'security_scan before containerize (it scans source dependencies); ' +
  'build_image before run_tests (tests run inside the built image); ' +
  'run_tests before run_migrations (migrations run as a post-test job); ' +
  'deploy before setup_monitoring (the monitoring agent installs onto the live host). ' +
  'Correct order: ' + GOLDEN_ORDER.join(' -> ') + '.';
